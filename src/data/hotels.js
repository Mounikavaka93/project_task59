function withStartingPrice(hotel) {
  const priceFrom = Math.min(...hotel.rooms.map((room) => room.price));
  return { ...hotel, priceFrom };
}

export const HOTELS = RAW_HOTELS.map(withStartingPrice);

export function getHotelById(id) {
  return HOTELS.find((hotel) => hotel.id === id) || null;
}
